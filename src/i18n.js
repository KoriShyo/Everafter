// Language support: English / Khmer.
// Owner-interface strings are keyed by their English text; invitation strings use short keys.
import { useSyncExternalStore } from 'react';

const KEY = 'everafter.lang';
let uiLang = (() => {
  try {
    return localStorage.getItem(KEY) === 'km' ? 'km' : 'en';
  } catch {
    return 'en';
  }
})();
const listeners = new Set();
if (typeof document !== 'undefined') document.documentElement.lang = uiLang;

export function setUiLang(lang) {
  uiLang = lang === 'km' ? 'km' : 'en';
  try {
    localStorage.setItem(KEY, uiLang);
  } catch {
    /* per-viewer preference only */
  }
  document.documentElement.lang = uiLang;
  listeners.forEach((l) => l());
}
export const getUiLang = () => uiLang;
export function useUiLang() {
  return useSyncExternalStore(
    (l) => {
      listeners.add(l);
      return () => listeners.delete(l);
    },
    () => uiLang,
  );
}

const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s);

export function translate(lang, s, vars) {
  return fill(lang === 'km' ? (KM[s] ?? s) : s, vars);
}
/** Hook returning t(englishText, vars) for the owner interface. */
export function useT() {
  const lang = useUiLang();
  const t = (s, vars) => translate(lang, s, vars);
  t.lang = lang;
  return t;
}

